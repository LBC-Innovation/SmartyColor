// Generates src/lib/print/fonts/*.ts base64 modules from the OFL TTFs next to them.
// Run: node scripts/generate-print-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "src/lib/print/fonts");
const fonts = [
  { ttf: "ptserif/PT_Serif-Web-Italic.ttf", out: "noteFont.ts", name: "noteFontBase64", label: "PT Serif Italic (SIL OFL)" },
  { ttf: "ptsans/PT_Sans-Web-Regular.ttf", out: "storybookRegularFont.ts", name: "storybookRegularFontBase64", label: "PT Sans Regular (SIL OFL)" },
  { ttf: "ptsans/PT_Sans-Web-Bold.ttf", out: "storybookBoldFont.ts", name: "storybookBoldFontBase64", label: "PT Sans Bold (SIL OFL)" },
];
for (const f of fonts) {
  const b64 = readFileSync(join(dir, f.ttf)).toString("base64");
  writeFileSync(
    join(dir, f.out),
    `// Generated by scripts/generate-print-fonts.mjs from ${f.ttf}. Do not edit.\n// ${f.label}; license in the font's OFL.txt.\n/* eslint-disable */\nexport const ${f.name} = "${b64}";\n`,
  );
  console.log("wrote", f.out, b64.length);
}
