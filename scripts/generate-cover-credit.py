"""
Traces the lettering of the back-cover credit ("Made with" / [heart] / "By
ColorfulMemories.Net") from the Fredoka font into plain vector outlines, written
to src/lib/print/coverCreditArt.ts. With outlines the print PDF needs no
embedded font, the server needs no fonts installed, and the wizard preview draws
exactly what prints.

Needs fontTools and a Fredoka TTF (variable or static):
  pip install fonttools
  python scripts/generate-cover-credit.py [path/to/Fredoka.ttf]
"""
import os
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.join(os.path.dirname(__file__), "..")
FONT = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/.fonts/Fredoka-Bold.ttf")
WEIGHT = 600

font = TTFont(FONT)
if "fvar" in font:
    axes = {a.axisTag: a.defaultValue for a in font["fvar"].axes}
    axes["wght"] = WEIGHT
    font = instancer.instantiateVariableFont(font, axes)

glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
upm = font["head"].unitsPerEm
ascent = font["hhea"].ascent


def trace(text):
    """One SVG path for a run of text: y down, origin at the top-left, baseline at `ascent`."""
    parts, x = [], 0
    for ch in text:
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, ascent)))
        parts.append(pen.getCommands())
        x += glyphs[name].width
    return "".join(parts), x


before, before_w = trace("Made with")
after, after_w = trace("By ColorfulMemories.Net")

with open(os.path.join(ROOT, "src/lib/print/coverCreditArt.ts"), "w") as out:
    out.write(
        f'''/**
 * Lettering of the back-cover credit, traced from Fredoka {WEIGHT} into outlines.
 * Generated by scripts/generate-cover-credit.py — do not edit by hand.
 * Paths are in font units, y down, with the origin at the top-left of the line.
 */
export const COVER_CREDIT_ART = {{
  unitsPerEm: {upm},
  /** Baseline, measured down from the top of the line. */
  ascent: {ascent},
  before: {{ width: {before_w}, d: "{before}" }},
  after: {{ width: {after_w}, d: "{after}" }},
}} as const;
'''
    )
print(upm, ascent, before_w, after_w, len(before) + len(after))
