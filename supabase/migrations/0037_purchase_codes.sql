-- Purchase codes: a pre-paid book bundle an admin creates (and emails, texts or prints), which a
-- customer binds to one album. The album then has its own allowance, spent before the wallet:
--
--   * included_pages   coloring pages made from that album's photos
--   * edits_per_page   AI touch-ups on each included page
--   * portraits_per_page "convert to portrait" on each included page
--   * one printed book in binding_id with standard shipping (backs_included: each page may have
--     a blank or lined back at no extra cost)
--
-- Anything past that (more pages, more edits, a different binding, faster shipping) is charged
-- to the customer's wallet as usual, and the app labels it as extra.
--
-- Numbered 0037: 0036 is the acquisition-tracking migration already applied to production.

create table if not exists public.purchase_codes (
  id                 uuid primary key default gen_random_uuid(),
  -- What the customer types or scans, e.g. CM-7KQ4-X9PD. Generated by the server, never chosen.
  code               text not null unique check (code ~ '^[A-Z0-9][A-Z0-9-]{5,31}$'),
  -- Admin-facing name of the batch, e.g. "Black Friday 2026".
  campaign           text not null check (char_length(campaign) between 1 and 80),
  -- utm_campaign on every link to this code.
  campaign_slug      text not null check (campaign_slug ~ '^[a-z0-9][a-z0-9-]{0,63}$'),
  included_pages     integer not null check (included_pages between 1 and 200),
  edits_per_page     integer not null default 3 check (edits_per_page between 0 and 20),
  portraits_per_page integer not null default 1 check (portraits_per_page between 0 and 5),
  binding_id         text not null check (binding_id in ('saddle_stitch', 'coil_bound', 'perfect_bound')),
  backs_included     boolean not null default true,
  shipping_level     text not null default 'MAIL',
  -- Most the code pays toward the book (print + standard shipping + tax). Null = no cap.
  max_book_cents     integer check (max_book_cents is null or max_book_cents > 0),
  -- Last day the code can be redeemed. Once bound to an album it does not expire.
  expires_at         timestamptz,
  recipient_name     text check (recipient_name is null or char_length(recipient_name) <= 120),
  recipient_email    text check (recipient_email is null or char_length(recipient_email) <= 254),
  recipient_phone    text check (recipient_phone is null or char_length(recipient_phone) <= 32),
  -- Shown to the recipient in the email and on the printed card.
  note               text check (note is null or char_length(note) <= 500),
  status             text not null default 'active' check (status in ('active', 'void')),
  created_by         uuid references auth.users (id) on delete set null,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  voided_at          timestamptz,
  voided_by          uuid references auth.users (id) on delete set null,
  redeemed_by        uuid references auth.users (id) on delete set null,
  redeemed_at        timestamptz,
  project_id         uuid references public.library_projects (id) on delete set null,
  -- First/last-touch campaign cookie at redemption (see src/lib/marketing/attribution.ts).
  redeem_attribution jsonb,
  -- Included pages claimed so far. Never goes down when a photo is deleted, so a page can't be
  -- made, downloaded and deleted to free its slot.
  pages_used         integer not null default 0 check (pages_used >= 0),
  -- The book this code paid for; cleared again if that order is canceled.
  book_order_id      uuid references public.book_orders (id) on delete set null,
  book_covered_cents integer
);

comment on table public.purchase_codes is
  'Pre-paid book bundles (purchase codes). Created on /admin/purchase-codes, redeemed into one album.';

