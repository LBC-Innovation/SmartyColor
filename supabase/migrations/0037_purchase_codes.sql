  code_id          uuid not null references public.purchase_codes (id) on delete cascade,
  photo_id         uuid not null references public.library_photos (id) on delete cascade,
  generations_used integer not null default 0 check (generations_used >= 0),
  portraits_used   integer not null default 0 check (portraits_used >= 0),
  created_at       timestamptz not null default now(),
  primary key (code_id, photo_id)
);

