-- Whether the album's purchase code pays for one AI action on a photo. With p_claim it also
-- records the use (call it inside the charge's transaction); without, it only answers.
--   generation: a photo already included gets one page, plus one more per portrait version made
--               under the code; a new photo is included while included pages remain.
--   portrait:   up to portraits_per_page on an included photo (a new photo is included first).
--   edit:       an included photo whose edit_count is under edits_per_page.
create or replace function public.purchase_code_covers(
  p_photo_id uuid,
  p_kind text,
  p_claim boolean default false
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_project uuid;
  v_edit_count integer;
  v_code public.purchase_codes%rowtype;
  v_use public.purchase_code_photos%rowtype;
  v_has_use boolean;
begin
  select project_id, edit_count into v_project, v_edit_count
  from public.library_photos
  where id = p_photo_id;
  if not found then
    return null;
  end if;

  if p_claim then
    select * into v_code from public.purchase_codes
    where project_id = v_project and status = 'active'
    for update;
  else
    select * into v_code from public.purchase_codes
    where project_id = v_project and status = 'active';
  end if;
  if not found then
    return null;
  end if;

  select * into v_use from public.purchase_code_photos
  where code_id = v_code.id and photo_id = p_photo_id;
  v_has_use := found;

  if p_kind = 'edit' then
    if v_has_use and v_edit_count < v_code.edits_per_page then
      return v_code.id;
    end if;
    return null;
  end if;

  if p_kind not in ('generation', 'portrait') then
    return null;
  end if;

  if v_has_use then
    if p_kind = 'generation' and v_use.generations_used >= 1 + v_use.portraits_used then
      return null;
    end if;
    if p_kind = 'portrait' and v_use.portraits_used >= v_code.portraits_per_page then
      return null;
    end if;
  elsif v_code.pages_used >= v_code.included_pages
     or (p_kind = 'portrait' and v_code.portraits_per_page = 0) then
    return null;
  end if;

  if p_claim then
    if not v_has_use then
      insert into public.purchase_code_photos (code_id, photo_id) values (v_code.id, p_photo_id);
      update public.purchase_codes set pages_used = pages_used + 1 where id = v_code.id;
    end if;
    update public.purchase_code_photos
    set
      generations_used = generations_used + case when p_kind = 'generation' then 1 else 0 end,
      portraits_used = portraits_used + case when p_kind = 'portrait' then 1 else 0 end
    where code_id = v_code.id and photo_id = p_photo_id;
  end if;

  return v_code.id;
end;
$$;

revoke all on function public.purchase_code_covers(uuid, text, boolean) from public, anon, authenticated;
grant execute on function public.purchase_code_covers(uuid, text, boolean) to service_role;

-- Undoes one claimed use when the result could not be saved. A photo left with no uses gives its
-- page slot back (this only runs straight after a failed save, never for a deleted photo).
create or replace function public.purchase_code_release(p_photo_id uuid, p_kind text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_use public.purchase_code_photos%rowtype;
begin
  select u.* into v_use
  from public.purchase_code_photos u
  join public.purchase_codes c on c.id = u.code_id
  join public.library_photos p on p.id = u.photo_id and p.project_id = c.project_id
  where u.photo_id = p_photo_id
  for update of u;
  if not found then
    return;
  end if;

  if p_kind = 'generation' then
    v_use.generations_used := greatest(v_use.generations_used - 1, 0);
  elsif p_kind = 'portrait' then
    v_use.portraits_used := greatest(v_use.portraits_used - 1, 0);
  else
    return;
  end if;

  if v_use.generations_used = 0 and v_use.portraits_used = 0 then
    delete from public.purchase_code_photos where code_id = v_use.code_id and photo_id = p_photo_id;
    update public.purchase_codes set pages_used = greatest(pages_used - 1, 0) where id = v_use.code_id;
  else
    update public.purchase_code_photos
    set generations_used = v_use.generations_used, portraits_used = v_use.portraits_used
    where code_id = v_use.code_id and photo_id = p_photo_id;
  end if;
end;
$$;

revoke all on function public.purchase_code_release(uuid, text) from public, anon, authenticated;
grant execute on function public.purchase_code_release(uuid, text) to service_role;

-- Same as 0022, plus: the album's purchase code pays first when it covers the action.
create or replace function public.charge_photo_usage(
  p_user_id uuid,
  p_photo_id uuid,
  p_kind text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sku text;
  v_item public.price_items%rowtype;
  v_balance integer;
  v_edit_count integer;
  v_cost integer;
  v_code uuid;
begin
  v_sku := case p_kind
    when 'generation' then 'ai.sheet_generation'
    when 'edit' then 'ai.sheet_edit'
    when 'portrait' then 'ai.photo_portrait'
  end;
  if v_sku is null then
    raise exception 'unknown usage kind';
  end if;

  select * into v_item from public.price_items where sku = v_sku;
  if not found or v_item.list_price_cents is null then
    raise exception 'price not configured for %', v_sku;
  end if;

  select credits_balance into v_balance
  from public.profiles
  where id = p_user_id
  for update;
  if not found then
    raise exception 'profile not found';
  end if;

  select edit_count into v_edit_count
  from public.library_photos
  where id = p_photo_id
  for update;
  if not found then
    raise exception 'photo not found';
  end if;

  v_cost := case when v_item.billable then v_item.list_price_cents else 0 end;
  if p_kind = 'edit' and v_edit_count < v_item.free_quota then
    v_cost := 0;
  end if;

  -- Free under the catalog anyway: leave the code's allowance alone.
  if v_cost > 0 then
    v_code := public.purchase_code_covers(p_photo_id, p_kind, true);
    if v_code is not null then
      v_cost := 0;
    end if;
  end if;

  if v_balance < v_cost then
    raise exception 'insufficient credits';
  end if;

  if p_kind = 'edit' then
    v_edit_count := v_edit_count + 1;
    update public.library_photos set edit_count = v_edit_count where id = p_photo_id;
  end if;

  if v_cost > 0 then
    v_balance := v_balance - v_cost;
    update public.profiles set credits_balance = v_balance where id = p_user_id;

    insert into public.credit_ledger (
      user_id, delta, balance_after, reason, reference_type, reference_id, price_sku, cogs_cents
    )
    values (
      p_user_id, -v_cost, v_balance,
      case p_kind
        when 'edit' then 'sheet_edit'
        when 'portrait' then 'photo_portrait'
        else 'sheet_generation'
      end,
      'library_photo', p_photo_id, v_sku, v_item.unit_cost_cents
    );
  end if;

  return jsonb_build_object(
    'chargedCents', v_cost,
    'creditsBalanceCents', v_balance,
    'editCount', v_edit_count,
    'purchaseCodeId', v_code
  );
end;
$$;

revoke all on function public.charge_photo_usage(uuid, uuid, text) from public, anon, authenticated;
grant execute on function public.charge_photo_usage(uuid, uuid, text) to service_role;

-- Same as 0022, plus: the order's purchase code pays covered_cents and the wallet the rest.
create or replace function public.place_book_order_with_credits(
  p_user_id uuid,
  p_order_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.book_orders%rowtype;
  v_balance integer;
  v_total integer;
  v_covered integer := 0;
  v_charge integer;
  v_code public.purchase_codes%rowtype;
begin
  select * into v_order
  from public.book_orders
  where id = p_order_id
    and user_id = p_user_id
    and deleted_at is null
  for update;

  if not found then
    raise exception 'order not found';
  end if;

  if v_order.status <> 'awaiting_payment' then
    raise exception 'order is not awaiting payment';
  end if;

  v_total := v_order.total_cents;
  if v_total is null or v_total <= 0 then
    raise exception 'order total is not set';
  end if;
  if v_order.lulu_cost_cents is not null and v_total < v_order.lulu_cost_cents then
    raise exception 'order priced below cost';
  end if;

  if v_order.purchase_code_id is not null and v_order.covered_cents > 0 then
    select * into v_code from public.purchase_codes
    where id = v_order.purchase_code_id
    for update;
    if not found or v_code.status <> 'active' or v_code.project_id is distinct from v_order.project_id
       or v_code.redeemed_by is distinct from p_user_id then
      raise exception 'purchase code is not valid for this order';
    end if;
    if v_code.book_order_id is not null and v_code.book_order_id <> p_order_id then
      raise exception 'purchase code already paid for a book';
    end if;
    v_covered := least(v_order.covered_cents, v_total);
    update public.purchase_codes
    set book_order_id = p_order_id, book_covered_cents = v_covered
    where id = v_code.id;
  end if;

  v_charge := v_total - v_covered;

  select credits_balance into v_balance
  from public.profiles
  where id = p_user_id
  for update;

  if not found then
    raise exception 'profile not found';
  end if;

  if v_balance < v_charge then
    raise exception 'insufficient credits';
  end if;

  if v_charge > 0 then
    v_balance := v_balance - v_charge;

    update public.profiles
    set credits_balance = v_balance
    where id = p_user_id;

    insert into public.credit_ledger (
      user_id, delta, balance_after, reason, reference_type, reference_id, note, price_sku, cogs_cents
    )
    values (
      p_user_id, -v_charge, v_balance, 'order_payment', 'book_order', p_order_id,
      case when v_covered > 0 then 'Book order payment (beyond purchase code)' else 'Book order payment' end,
      v_order.price_sku, v_order.lulu_cost_cents
    );
  end if;

  update public.book_orders
  set
    status = 'paid',
    payment_method = 'credits',
    credits_applied = v_charge,
    covered_cents = v_covered,
    paid_at = now(),
    updated_at = now()
  where id = p_order_id;

  return jsonb_build_object(
    'orderId', p_order_id,
    'status', 'paid',
    'creditsBalanceCents', v_balance,
    'creditsAppliedCents', v_charge,
    'coveredCents', v_covered
  );
end;
$$;

revoke all on function public.place_book_order_with_credits(uuid, uuid)
  from public, anon, authenticated;
grant execute on function public.place_book_order_with_credits(uuid, uuid)
  to service_role;

-- A canceled book gives its purchase code back, so the customer can order the book again.
-- (cancel_and_refund_book_order refunds only credits_applied, which is the wallet's part.)
create or replace function public.release_purchase_code_on_cancel()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'canceled' and old.status is distinct from 'canceled' then
    update public.purchase_codes
    set book_order_id = null, book_covered_cents = null
    where book_order_id = new.id;
  end if;
  return new;
end;
$$;

drop trigger if exists book_orders_release_purchase_code on public.book_orders;
create trigger book_orders_release_purchase_code
  after update of status on public.book_orders
  for each row
  execute function public.release_purchase_code_on_cancel();
